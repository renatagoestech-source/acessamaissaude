-- Código de ativação presencial de paciente — Supabase/PostgreSQL.
-- A UBS entrega um código numérico de uso único, válido por 15 minutos.
-- A aplicação guarda somente SHA-256 do código; DDL não é executada automaticamente.

CREATE TABLE IF NOT EXISTS public.patient_activation_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES public.pacientes(id) ON DELETE CASCADE,
    ubs_id VARCHAR(20) NOT NULL REFERENCES public.ubs(id) ON DELETE CASCADE,
    codigo_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL,
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    issued_by BIGINT NOT NULL REFERENCES public.administradores(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.patient_activation_codes ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_patient_activation_patient
    ON public.patient_activation_codes (paciente_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_patient_activation_expiry
    ON public.patient_activation_codes (expires_at);
