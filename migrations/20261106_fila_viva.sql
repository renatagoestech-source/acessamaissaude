-- Acessa+ Saúde — Fila Viva / encaminhamentos e reaproveitamento controlado de vagas
-- PostgreSQL/Supabase. Migração aditiva, idempotente; executar após backup/revisão.
-- Este sistema não executa DDL automaticamente em DATABASE_URL.

ALTER TABLE public.lista_espera
    ADD COLUMN IF NOT EXISTS encaminhado_em TIMESTAMP NULL,
    ADD COLUMN IF NOT EXISTS origem_ubs_id VARCHAR(20) NULL,
    ADD COLUMN IF NOT EXISTS protocolo VARCHAR(32) NULL,
    ADD COLUMN IF NOT EXISTS prioridade_categoria VARCHAR(120) NULL,
    ADD COLUMN IF NOT EXISTS prioridade_observacao VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS prioridade_validada_por BIGINT NULL,
    ADD COLUMN IF NOT EXISTS prioridade_validada_em TIMESTAMP NULL;

UPDATE public.lista_espera
SET encaminhado_em = COALESCE(encaminhado_em, criado_em, CURRENT_TIMESTAMP)
WHERE encaminhado_em IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_lista_espera_fv_protocolo
    ON public.lista_espera (protocolo);

CREATE INDEX IF NOT EXISTS idx_fv_lista_periodo
    ON public.lista_espera (ubs_id, especialidade, status, encaminhado_em);

ALTER TABLE public.consultas
    ADD COLUMN IF NOT EXISTS confirmacao_status VARCHAR(20) NOT NULL DEFAULT 'pendente',
    ADD COLUMN IF NOT EXISTS confirmada_em TIMESTAMP NULL;

CREATE INDEX IF NOT EXISTS idx_fv_consulta_confirmacao
    ON public.consultas (ubs_id, especialidade, data_consulta, confirmacao_status);

CREATE TABLE IF NOT EXISTS public.fila_viva_vagas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancelamento_consulta_id VARCHAR(60) NULL UNIQUE,
    ubs_id VARCHAR(20) NOT NULL,
    especialidade VARCHAR(120) NOT NULL,
    data_consulta DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'disponivel'
        CHECK (status IN ('disponivel','ofertada','preenchida')),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.fila_viva_vagas ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_fila_viva_vagas_filtro
    ON public.fila_viva_vagas (ubs_id, especialidade, data_consulta, status, criado_em);

CREATE TABLE IF NOT EXISTS public.fila_viva_ofertas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaga_id BIGINT NOT NULL REFERENCES public.fila_viva_vagas(id) ON DELETE CASCADE,
    lista_espera_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente'
        CHECK (status IN ('pendente','aceita','recusada','expirada')),
    expira_em TIMESTAMP NOT NULL,
    criado_por BIGINT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resposta_em TIMESTAMP NULL
);

ALTER TABLE public.fila_viva_ofertas ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_fila_viva_oferta_vaga_status
    ON public.fila_viva_ofertas (vaga_id, status);
CREATE INDEX IF NOT EXISTS idx_fila_viva_oferta_expira
    ON public.fila_viva_ofertas (status, expira_em);
